const licenseBlock = `//
// Licensed under the Apache License, Version 2.0 (the "License");
// you may not use this file except in compliance with the License.

package main
`

// licenseAndSPDX carries the tag in a comment of its own below the header, the
// layout private/underlay/ebpf uses.
const licenseAndSPDX = `//
// Licensed under the Apache License, Version 2.0 (the "License");
// you may not use this file except in compliance with the License.

// SPDX-License-Identifier: Apache-2.0

package main
`

func TestParseHeaderClaims(t *testing.T) {
	testCases := map[string]struct {
		file   string
		claims []claim
	}{
		"single holder": {
			file:   "// Copyright 2020 Anapaya Systems\n" + licenseBlock,
			claims: []claim{{year: 2020, holders: []string{"Anapaya Systems"}}},
		},
		"one per line": {
			file: "// Copyright 2020 Anapaya Systems\n" +
				"// Copyright 2026 SCION Association\n" + licenseBlock,
			claims: []claim{
				{year: 2020, holders: []string{"Anapaya Systems"}},
				{year: 2026, holders: []string{"SCION Association"}},
			},
		},
		"holders sharing a line": {
			file: "// Copyright 2026 SCION Association, Anapaya Systems\n" + licenseBlock,
			claims: []claim{
				{year: 2026, holders: []string{"SCION Association", "Anapaya Systems"}},
			},
		},
		"holders spaced unevenly": {
			file: "// Copyright 2020 ETH Zurich,Anapaya Systems  \n" + licenseBlock,
			claims: []claim{
				{year: 2020, holders: []string{"ETH Zurich", "Anapaya Systems"}},
			},
		},
		"a holder from outside this repository": {
			file:   "// Copyright 2013 The Prometheus Authors\n" + licenseBlock,
			claims: []claim{{year: 2013, holders: []string{"The Prometheus Authors"}}},
		},
		"spdx tag below the header": {
			file:   "// Copyright 2025 SCION Association\n" + licenseAndSPDX,
			claims: []claim{{year: 2025, holders: []string{"SCION Association"}}},
		},
		"license block without a notice": {
			file:   licenseBlock,
			claims: nil,
		},
	}
	for name, tc := range testCases {
		t.Run(name, func(t *testing.T) {
			lines, _ := splitLines(tc.file)
			hdr, reason := parseHeader(lines)
			require.Empty(t, string(reason))
			assert.Equal(t, tc.claims, hdr.claims)
		})
	}
}

func TestParseHeaderSkips(t *testing.T) {
	testCases := map[string]struct {
		file   string
		reason skipReason
	}{
		"generated": {
			file:   "// Code generated by MockGen. DO NOT EDIT.\n// Source: whatever\n",
			reason: skipGenerated,
		},
		"generated below a package comment": {
			file: "// Package api provides things.\n//\n" +
				"// Code generated by oapi-codegen version v1 DO NOT EDIT.\n",
			reason: skipGenerated,
		},
		"third-party notice above an spdx line": {
			file: "// Copyright (c) Tailscale Inc & AUTHORS\n" +
				"// SPDX-License-Identifier: BSD-3-Clause\n\npackage stun\n",
			reason: skipForeign,
		},
		"third-party notice under an spdx line": {
			file: "// SPDX-License-Identifier: BSD-3-Clause\n//\n" +
				"// Copyright (c) 2016 Grant Ayers\n" + licenseBlock,
			reason: skipForeign,
		},
		// Claims have to lead the header. A tag above them is not read as a
		// prefix, so the notice below it looks like someone else's.
		"our own notice under an spdx line": {
			file: "// SPDX-License-Identifier: Apache-2.0\n//\n" +
				"// Copyright 2025 SCION Association\n" + licenseBlock,
			reason: skipForeign,
		},
		"third-party MIT notice": {
			file:   "// MIT License\n//\n// Copyright (c) 2017 Ben Toews.\n//\n",
			reason: skipForeign,
		},
		"misspaced notice": {
			file:   "//  Copyright 2020 Smallstep Labs, Inc.\n" + licenseBlock,
			reason: skipForeign,
		},
		"an empty holder": {
			file:   "// Copyright 2015 SCION Association,\n" + licenseBlock,
			reason: skipForeign,
		},
		"foreign notice below ours": {
			file: "// Copyright 2020 Anapaya Systems\n" +
				"// Portions copyright 2011 The Go Authors.\n" + licenseBlock,
			reason: skipForeign,
		},
		"notice below the package clause": {
			file:   "package main\n\n// Copyright 2020 Anapaya Systems\n",
			reason: skipNoHeader,
		},
		"no header at all": {
			file:   "package main\n\nfunc main() {}\n",
			reason: skipNoHeader,
		},
	}
	for name, tc := range testCases {
		t.Run(name, func(t *testing.T) {
			lines, _ := splitLines(tc.file)
			hdr, reason := parseHeader(lines)
			assert.Nil(t, hdr)
			assert.Equal(t, tc.reason, reason)
		})
	}
}

func TestUpdate(t *testing.T) {
	testCases := map[string]struct {
		before []string
		org    string
		// after is nil when nothing needs to change.
		after []string
	}{
		"a new organization goes below the others": {
			before: []string{"// Copyright 2019 Anapaya Systems"},
			org:    "SCION Association",
			after: []string{
				"// Copyright 2019 Anapaya Systems",
				"// Copyright 2026 SCION Association",
			},
		},
		"a line of its own moves in place": {
			before: []string{
				"// Copyright 2019 Anapaya Systems",
				"// Copyright 2025 SCION Association",
			},
			org: "Anapaya Systems",
			after: []string{
				"// Copyright 2026 Anapaya Systems",
				"// Copyright 2025 SCION Association",
			},
		},
		"several lines of its own become one": {
			before: []string{
				"// Copyright 2017 ETH Zurich",
				"// Copyright 2020 ETH Zurich",
			},
			org:   "ETH Zurich",
			after: []string{"// Copyright 2026 ETH Zurich"},
		},
		"an older shared line loses it": {
			before: []string{
				"// Copyright 2018 ETH Zurich, Anapaya Systems",
				"// Copyright 2020 ETH Zurich",
			},
			org: "ETH Zurich",
			after: []string{
				"// Copyright 2018 Anapaya Systems",
				"// Copyright 2026 ETH Zurich",
			},
		},
		"a shared line splits in place": {
			before: []string{"// Copyright 2025 SCION Association, Anapaya Systems"},
			org:    "SCION Association",
			after: []string{
				"// Copyright 2026 SCION Association",
				"// Copyright 2025 Anapaya Systems",
			},
		},
		"a shared line splits around a later holder": {
			before: []string{"// Copyright 2020 ETH Zurich, Anapaya Systems"},
			org:    "Anapaya Systems",
			after: []string{
				"// Copyright 2020 ETH Zurich",
				"// Copyright 2026 Anapaya Systems",
			},
		},
		"a shared line splits around a holder in the middle": {
			before: []string{
				"// Copyright 2020 SCION Association, ETH Zurich, Anapaya Systems",
			},
			org: "ETH Zurich",
			after: []string{
				"// Copyright 2020 SCION Association",
				"// Copyright 2026 ETH Zurich",
				"// Copyright 2020 Anapaya Systems",
			},
		},
		"the newest line moves also when shared, an older one goes": {
			before: []string{
				"// Copyright 2017 ETH Zurich",
				"// Copyright 2018 ETH Zurich, Anapaya Systems",
				"// Copyright 2025 SCION Association",
			},
			org: "ETH Zurich",
			after: []string{
				"// Copyright 2026 ETH Zurich",
				"// Copyright 2018 Anapaya Systems",
				"// Copyright 2025 SCION Association",
			},
		},
		"claims listed newest first keep their order": {
			before: []string{
				"// Copyright 2025 SCION Association",
				"// Copyright 2021 Anapaya Systems",
			},
			org: "ETH Zurich",
			after: []string{
				"// Copyright 2025 SCION Association",
				"// Copyright 2021 Anapaya Systems",
				"// Copyright 2026 ETH Zurich",
			},
		},
		"a holder spelled otherwise is another holder": {
			before: []string{"// Copyright 2020 Scion Association"},
			org:    "SCION Association",
			after: []string{
				"// Copyright 2020 Scion Association",
				"// Copyright 2026 SCION Association",
			},
		},
		"a holder from outside this repository gets a claim below": {
			before: []string{"// Copyright 2013 The Prometheus Authors"},
			org:    "SCION Association",
			after: []string{
				"// Copyright 2013 The Prometheus Authors",
				"// Copyright 2026 SCION Association",
			},
		},
		"already claimed": {
			before: []string{"// Copyright 2026 SCION Association"},
			org:    "SCION Association",
		},
		"already claimed on a shared line": {
			before: []string{
				"// Copyright 2019 SCION Association",
				"// Copyright 2026 ETH Zurich, SCION Association",
			},
			org: "SCION Association",
		},
		"a year is never moved back": {
			before: []string{"// Copyright 2027 SCION Association"},
			org:    "SCION Association",
		},
	}
	for name, tc := range testCases {
		t.Run(name, func(t *testing.T) {
			lines, _ := splitLines(strings.Join(tc.before, "\n") + "\n" + licenseBlock)
			hdr, reason := parseHeader(lines)
			require.Empty(t, string(reason))
			assert.Equal(t, tc.after, hdr.update(lines, tc.org, 2026))
		})
	}
}

func TestUpdateReplacesOnlyTheYear(t *testing.T) {
	lines, _ := splitLines("// Copyright 2020 Anapaya Systems  \n" + licenseBlock)
	hdr, reason := parseHeader(lines)
	require.Empty(t, string(reason))
	assert.Equal(t, []string{"// Copyright 2026 Anapaya Systems  "},
		hdr.update(lines, "Anapaya Systems", 2026))
}

func TestRender(t *testing.T) {
	testCases := map[string]struct {
		before string
		after  string
	}{
		"claim added below the others": {
			before: "// Copyright 2020 Anapaya Systems\n" + licenseBlock,
			after: "// Copyright 2020 Anapaya Systems\n" +
				"// Copyright 2026 SCION Association\n" + licenseBlock,
		},
		"shared line split in place": {
			before: "// Copyright 2019 ETH Zurich\n" +
				"// Copyright 2025 SCION Association, Anapaya Systems\n" + licenseBlock,
			after: "// Copyright 2019 ETH Zurich\n" +
				"// Copyright 2026 SCION Association\n" +
				"// Copyright 2025 Anapaya Systems\n" + licenseBlock,
		},
		"spdx tag below the header preserved": {
			before: "// Copyright 2025 SCION Association\n" + licenseAndSPDX,
			after:  "// Copyright 2026 SCION Association\n" + licenseAndSPDX,
		},
		"claim inserted above a bare license": {
			before: licenseBlock,
			after:  "// Copyright 2026 SCION Association\n" + licenseBlock,
		},
		"claim and separator inserted above a license opening the file": {
			before: strings.TrimPrefix(licenseBlock, "//\n"),
			after:  "// Copyright 2026 SCION Association\n" + licenseBlock,
		},
	}
	for name, tc := range testCases {
		t.Run(name, func(t *testing.T) {
			lines, eol := splitLines(tc.before)
			hdr, reason := parseHeader(lines)
			require.Empty(t, string(reason))
			out := hdr.render(lines, hdr.update(lines, "SCION Association", 2026))
			assert.Equal(t, tc.after, strings.Join(out, eol))
		})
	}
}

func TestRenderKeepsCRLF(t *testing.T) {
	crlf := func(s string) string { return strings.ReplaceAll(s, "\n", "\r\n") }
	lines, eol := splitLines(crlf("// Copyright 2020 Anapaya Systems\n" + licenseBlock))
	require.Equal(t, "\r\n", eol)
	hdr, reason := parseHeader(lines)
	require.Empty(t, string(reason))
	out := strings.Join(hdr.render(lines, hdr.update(lines, "ETH Zurich", 2026)), eol)
	assert.Equal(t, crlf("// Copyright 2020 Anapaya Systems\n"+
		"// Copyright 2026 ETH Zurich\n"+licenseBlock), out)
}
