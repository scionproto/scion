// Package clab is the harness for containerlab system tests. An [Environment]
// generates a SCION topology with testgen, deploys it with containerlab, and
// tears it down again, collecting the node logs. Together with [PhasedTest] and
// the clab_system_test macro (system_test.bzl), a test can run all phases at
// once, or each phase on its own against a lab that stays deployed.
//
// The tests are built to run under bazel only: the node image and the binaries
// are passed in through environment variables that the clab_system_test macro
// sets. The only external dependency is the clab command itself.
package clab

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"github.com/bazelbuild/rules_go/go/runfiles"
	"github.com/stretchr/testify/require"

	"github.com/scionproto/scion/pkg/addr"
)

var (
	dockerFlag = flag.String("docker", "docker", "docker command (e.g. \"sudo docker\")")
	clabFlag   = flag.String("clab", "clab", "containerlab command")
	// artifactsFlag pins the working directory, where the lab is generated and
	// deployed. See NewEnvironment for the default.
	artifactsFlag = flag.String("artifacts", "",
		"working directory for the lab (default: TEST_TMPDIR/clab when running all "+
			"phases, else a fixed directory per lab under the system temp dir)")
)

// Environment variables through which the clab_system_test macro passes the
// lab artifacts. They hold $(rootpath ...) values.
const (
	EnvNodeImageTar         = "CLAB_NODE_IMAGE_TAR"
	EnvTestgenBin           = "TESTGEN_BIN"
	EnvAwaitConnectivityBin = "AWAIT_CONNECTIVITY_BIN"
)

const (
	// nodeImage is the image the node image tarball loads.
	nodeImage = "scion/clab-node:latest"
	// nodeLogDir is where the node controller writes the per-service logs.
	nodeLogDir     = "/var/log/scion"
	commandTimeout = 10 * time.Minute
	dockerTimeout  = time.Minute
	destroyTimeout = 5 * time.Minute

	workDirPerm os.FileMode = 0o755
)

// Environment is a containerlab lab generated by testgen.
type Environment struct {
	// LabName is the containerlab lab name. Container names are
	// clab-<LabName>-<node>.
	LabName string
	// WorkDir is where the lab is generated and deployed. It is deliberately
	// not under the bazel outputs directory: the containers run as root and
	// write into the bind-mounted gen/ tree, so it ends up with root-owned
	// files that bazel cannot collect as outputs.
	WorkDir string
	// GenDir is the testgen output directory, WorkDir/gen.
	GenDir string
	// ClabFile is the containerlab topology file.
	ClabFile string
	// OutputsDir is the bazel undeclared outputs directory, or empty when not
	// running under bazel test. Collected artifacts are written there.
	OutputsDir string
}

// NewEnvironment returns the environment of the lab with the given name. It
// does not deploy anything; see Deploy.
//
// The working directory is the -artifacts flag, if set. Otherwise, when all
// phases run in one go, it is TEST_TMPDIR/clab. When the phases run in
// separate invocations, it is a fixed directory per lab, so that a later
// phase finds the lab of an earlier one.
func NewEnvironment(t *testing.T, phased PhasedTest, labName string) *Environment {
	t.Helper()
	dir := *artifactsFlag
	if dir == "" {
		if tmp := os.Getenv("TEST_TMPDIR"); tmp != "" && phased.Default() {
			dir = filepath.Join(tmp, "clab")
		} else {
			dir = filepath.Join(os.TempDir(), "scion-clab", labName)
		}
	}
	require.NoError(t, os.MkdirAll(dir, workDirPerm))
	dir, err := filepath.Abs(dir)
	require.NoError(t, err)

	e := &Environment{
		LabName:    labName,
		WorkDir:    dir,
		GenDir:     filepath.Join(dir, "gen"),
		ClabFile:   filepath.Join(dir, "gen", labName+".clab.yml"),
		OutputsDir: os.Getenv("TEST_UNDECLARED_OUTPUTS_DIR"),
	}
	t.Logf("lab %q: work dir %s", labName, e.WorkDir)
	if e.OutputsDir != "" {
		t.Logf("lab %q: outputs dir %s", labName, e.OutputsDir)
	}
	return e
}

// Deploy loads the node image, generates the topology from topoFile with
// testgen (passing testgenArgs on), deploys it with containerlab, and waits
// until the beaconing established full connectivity. Any failure fails the
// test.
func (e *Environment) Deploy(t *testing.T, topoFile string, testgenArgs ...string) {
	t.Helper()
	t.Log("--- setup: loading node image")
	e.Run(t, *dockerFlag, "load", "--input", RunfileEnv(t, EnvNodeImageTar))

	t.Log("--- setup: generating topology")
	e.removeGenDir(t)
	require.NoError(t, os.MkdirAll(e.GenDir, workDirPerm))
	args := append([]string{
		"--topo", Runfile(t, topoFile),
		"-o", e.GenDir,
		"--name", e.LabName,
	}, testgenArgs...)
	e.Run(t, RunfileEnv(t, EnvTestgenBin), args...)
	e.CollectFile(t, e.ClabFile, e.LabName+".clab.yml")
	e.CollectFile(t, filepath.Join(e.GenDir, "network-allocations.yml"),
		"network-allocations.yml")

	t.Log("--- setup: deploying containerlab topology")
	e.Run(t, *clabFlag, "deploy", "--reconfigure", "-t", e.ClabFile)

	e.AwaitConnectivity(t)
}

// AwaitConnectivity waits until the beaconing established full connectivity.
func (e *Environment) AwaitConnectivity(t *testing.T) {
	t.Helper()
	t.Log("--- waiting for connectivity")
	e.Run(t, RunfileEnv(t, EnvAwaitConnectivityBin), "-gen", e.GenDir)
}

// Destroy collects the logs of all lab containers into the outputs directory
// and destroys the lab. A lab that was never generated is skipped. A failing
// destroy fails the test, but does not stop it.
func (e *Environment) Destroy(t *testing.T) {
	t.Helper()
	if _, err := os.Stat(e.ClabFile); err != nil {
		t.Logf("--- teardown: no clab topology at %s, skipping", e.ClabFile)
		return
	}
	e.collectNodeLogs(t)

	t.Log("--- teardown: destroying containerlab topology")
	ctx, cancel := context.WithTimeout(context.Background(), destroyTimeout)
	defer cancel()
	name, args := splitCmd(*clabFlag, "destroy", "--cleanup", "-t", e.ClabFile)
	cmd := exec.CommandContext(ctx, name, args...)
	cmd.Dir = e.WorkDir
	out, err := cmd.CombinedOutput()
	if len(out) > 0 {
		t.Logf("%s", out)
	}
	if err != nil {
		t.Errorf("clab destroy failed: %s", err)
	}
}

// Container returns the name of the container of an AS's host, e.g.
// clab-scion-1-ff00_0_110-host-1.
func (e *Environment) Container(ia addr.IA, host string) string {
	iaFile := addr.FormatIA(ia, addr.WithFileSeparator())
	return fmt.Sprintf("clab-%s-%s-%s", e.LabName, iaFile, host)
}

// DockerCmd returns the docker command, as passed to the -docker flag. Test
// drivers that exec into the nodes take it as their --docker argument.
func (e *Environment) DockerCmd() string {
	return *dockerFlag
}

// Run executes a command in the working directory, logs its combined output,
// and fails the test if it exits non-zero. It returns the combined output.
func (e *Environment) Run(t *testing.T, command string, args ...string) []byte {
	t.Helper()
	out, err := e.Exec(t, command, args...)
	require.NoError(t, err, "command failed: %s %v", command, args)
	return out
}

// Exec executes a command in the working directory and logs its combined
// output. Unlike Run, it does not fail the test, so that the caller can
// collect the output first.
func (e *Environment) Exec(t *testing.T, command string, args ...string) ([]byte, error) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), commandTimeout)
	defer cancel()
	name, full := splitCmd(command, args...)
	t.Logf("$ %s %v", name, full)
	cmd := exec.CommandContext(ctx, name, full...)
	cmd.Dir = e.WorkDir
	out, err := cmd.CombinedOutput()
	if len(out) > 0 {
		t.Logf("%s", out)
	}
	return out, err
}

// Docker runs a docker command with the given timeout and returns its combined
// output. Unlike Exec, it does not log.
func (e *Environment) Docker(timeout time.Duration, args ...string) ([]byte, error) {
	ctx, cancel := context.WithTimeout(context.Background(), timeout)
	defer cancel()
	name, full := splitCmd(*dockerFlag, args...)
	cmd := exec.CommandContext(ctx, name, full...)
	cmd.Dir = e.WorkDir
	return cmd.CombinedOutput()
}

// Collect writes data into the outputs directory under name, so that bazel
// gathers it as an undeclared output. It is best-effort, and a no-op outside
// of bazel test.
func (e *Environment) Collect(t *testing.T, data []byte, name string) {
	t.Helper()
	if e.OutputsDir == "" {
		return
	}
	dst := filepath.Join(e.OutputsDir, name)
	if err := os.MkdirAll(filepath.Dir(dst), workDirPerm); err != nil {
		t.Logf("collect %s: %s", name, err)
		return
	}
	if err := os.WriteFile(dst, data, 0o644); err != nil {
		t.Logf("collect %s: %s", name, err)
	}
}

// CollectFile copies the file at src into the outputs directory under name.
// See Collect.
func (e *Environment) CollectFile(t *testing.T, src, name string) {
	t.Helper()
	if e.OutputsDir == "" {
		return
	}
	data, err := os.ReadFile(src)
	if err != nil {
		t.Logf("collect %s: %s", name, err)
		return
	}
	e.Collect(t, data, name)
}

// collectNodeLogs gathers the logs of every container in the lab into
// <outputs>/logs:
//
//   - <container>.log: `docker logs`, the controller's merged stream of all
//     supervised services (prefixed per service);
//   - <container>/: the per-service log files from /var/log/scion.
//
// It is best-effort: failures are logged, never fatal, so teardown proceeds.
func (e *Environment) collectNodeLogs(t *testing.T) {
	t.Helper()
	if e.OutputsDir == "" {
		return
	}
	logDir := filepath.Join(e.OutputsDir, "logs")
	if err := os.MkdirAll(logDir, workDirPerm); err != nil {
		t.Logf("collect node logs: %s", err)
		return
	}
	containers, err := e.containers()
	if err != nil {
		t.Logf("collect node logs: listing containers: %s", err)
		return
	}
	t.Logf("--- teardown: collecting logs of %d containers into %s", len(containers), logDir)
	for _, c := range containers {
		out, err := e.Docker(dockerTimeout, "logs", c)
		if err != nil {
			t.Logf("collect node logs: docker logs %s: %s", c, err)
		}
		e.Collect(t, out, filepath.Join("logs", c+".log"))

		if out, err := e.Docker(dockerTimeout, "cp", c+":"+nodeLogDir,
			filepath.Join(logDir, c)); err != nil {
			t.Logf("collect node logs: docker cp %s: %s: %s", c, err, out)
		}
	}
}

// containers returns the names of all containers (running or not) that
// containerlab created for the lab, identified by its containerlab label.
func (e *Environment) containers() ([]string, error) {
	out, err := e.Docker(dockerTimeout, "ps", "--all",
		"--filter", "label=containerlab="+e.LabName,
		"--format", "{{.Names}}",
	)
	if err != nil {
		return nil, fmt.Errorf("%w: %s", err, out)
	}
	return strings.Fields(string(out)), nil
}

// removeGenDir removes the gen/ tree of a previous run. The containers of
// that run wrote root-owned files into it, which the test user may not be
// able to remove. In that case, the tree is removed from within a container
// of the node image.
func (e *Environment) removeGenDir(t *testing.T) {
	t.Helper()
	err := os.RemoveAll(e.GenDir)
	if err == nil {
		return
	}
	t.Logf("removing %s: %s; retrying as root in a container", e.GenDir, err)
	out, err := e.Docker(dockerTimeout, "run", "--rm",
		"-v", e.WorkDir+":/work",
		"--entrypoint", "rm",
		nodeImage, "-rf", "/work/gen",
	)
	require.NoError(t, err, "removing %s: %s", e.GenDir, out)
}

// EnvOr returns the value of the environment variable name, or def if the
// variable is unset or empty. Tests use it for flag defaults that the bazel
// target sets through its env attribute.
func EnvOr(name, def string) string {
	if v := os.Getenv(name); v != "" {
		return v
	}
	return def
}

// RunfileEnv resolves the bazel artifact whose $(rootpath ...) is in the given
// environment variable. It fails the test if the variable is not set.
func RunfileEnv(t *testing.T, name string) string {
	t.Helper()
	v := os.Getenv(name)
	require.NotEmptyf(t, v, "environment variable %s must be set (run via the bazel target)", name)
	return Runfile(t, v)
}

// Runfile resolves a path that is either absolute, a $(rootpath ...) runfiles
// path, or (for a user-supplied override) relative to the working directory.
func Runfile(t *testing.T, path string) string {
	t.Helper()
	if filepath.IsAbs(path) {
		return path
	}
	if abs, err := resolveRunfile(path); err == nil {
		if _, err := os.Stat(abs); err == nil {
			return abs
		}
	}
	abs, err := filepath.Abs(path)
	require.NoErrorf(t, err, "resolving path %q", path)
	if _, err := os.Stat(abs); errors.Is(err, os.ErrNotExist) {
		require.Failf(t, "file not found", "neither a runfile nor a local file: %q", path)
	}
	return abs
}

// resolveRunfile resolves a $(rootpath ...) value (a runfiles-root-relative
// path) to an absolute filesystem path. $(rootpath) for an external repo emits
// "external/<repo>/..."; rules_go runfiles want "<repo>/...". For the main repo
// it emits a bare path, which must be qualified with the main repo's canonical
// name.
func resolveRunfile(rootpath string) (string, error) {
	if rest, ok := strings.CutPrefix(rootpath, "external/"); ok {
		return runfiles.Rlocation(rest)
	}
	// Main repo: try the canonical Bzlmod name first, then the path as-is for
	// older runfiles layouts.
	if abs, err := runfiles.Rlocation("_main/" + rootpath); err == nil {
		return abs, nil
	}
	return runfiles.Rlocation(rootpath)
}

// splitCmd splits a (possibly multi-word) command like "sudo docker" into its
// executable and leading arguments, then appends args.
func splitCmd(command string, args ...string) (name string, argv []string) {
	fields := strings.Fields(command)
	if len(fields) == 0 {
		return command, args
	}
	return fields[0], append(fields[1:], args...)
}
